import https from 'node:https'
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const titleKeywords = {
  易学: ['周易', '易經', '易傳', '易學', '易說', '易解', '卦', '河圖', '洛書', '皇極', '太玄', '乾鑿度'],
  堪舆: ['地理', '青囊', '葬', '龍', '風水', '陽宅', '宅經', '堪輿', '天玉', '玉尺', '雪心'],
  子平: ['子平', '三命', '命理', '滴天髓', '窮通', '神峰', '命書', '五行精紀', '星平'],
  占筮: ['卜', '筮', '易林', '六爻', '梅花', '火珠', '斷易', '易隱', '黃金策'],
  斗数: ['紫微', '斗數', '星命', '果老'],
  三式: ['奇門', '遁甲', '六壬', '太乙'],
  择日: ['擇日', '通書', '協紀', '星歷', '選擇', '玉匣'],
  相法: ['相法', '神相', '麻衣', '相理', '太清神鑒', '人倫'],
  文字: ['說文', '字典', '廣韻', '玉篇', '集韻', '爾雅', '釋名', '方言'],
}
const categoryQueries = {
  易学: '周易 OR 易經 OR 易傳 OR 卦',
  堪舆: '堪輿 OR 風水 OR 地理 OR 陽宅 OR 青囊',
  子平: '子平 OR 命理 OR 三命 OR 滴天髓',
  占筮: '卜筮 OR 六爻 OR 梅花易數 OR 易林',
  斗数: '紫微斗數 OR 星命',
  三式: '奇門遁甲 OR 六壬 OR 太乙',
  择日: '擇日 OR 通書 OR 協紀辨方 OR 星歷',
  相法: '神相 OR 相法 OR 麻衣',
  文字: '說文解字 OR 字典 OR 廣韻 OR 玉篇',
}
const excludedTitles = new Set(['中天紫微星真寶懺', '太上六壬明鑑符陰經'])

function requestJson(url, family = 6) {
  return new Promise((resolve, reject) => {
    const request = https.get(url, { family, headers: { 'User-Agent': 'XuanshuStudio/0.1 public-domain catalog sync' } }, (response) => {
      if (response.statusCode !== 200) {
        response.resume()
        const error = new Error(`HTTP ${response.statusCode}`)
        error.statusCode = response.statusCode
        reject(error)
        return
      }
      let body = ''
      response.setEncoding('utf8')
      response.on('data', (chunk) => { body += chunk })
      response.on('end', () => {
        try { resolve(JSON.parse(body)) } catch { reject(new Error('Invalid JSON')) }
      })
    })
    request.setTimeout(30_000, () => request.destroy(new Error('Request timeout')))
    request.on('error', reject)
  })
}

async function fetchJson(url) {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try { return await requestJson(url, 6) } catch (ipv6Error) {
      if (ipv6Error.statusCode === 429) {
        await new Promise((resolve) => setTimeout(resolve, 2_000 * (attempt + 1)))
        continue
      }
      try { return await requestJson(url, 4) } catch {
        if (attempt === 4) throw ipv6Error
        await new Promise((resolve) => setTimeout(resolve, 1_000 * (attempt + 1)))
      }
    }
  }
  throw new Error('Public library search exhausted retries')
}

const records = new Map()
const counts = new Map()
const tasks = Object.entries(categoryQueries).map(([category, query]) => ({ category, query }))
let taskIndex = 0

async function scanWorker() {
  while (taskIndex < tasks.length) {
    const { category, query } = tasks[taskIndex++]
    const params = new URLSearchParams({
      action: 'query', format: 'json', formatversion: '2', list: 'search',
      srsearch: query, srnamespace: '0', srlimit: '100', srprop: 'wordcount|timestamp',
    })
    const payload = await fetchJson(`https://zh.wikisource.org/w/api.php?${params}`)
    const results = payload?.query?.search || []
    counts.set(category, (counts.get(category) || 0) + results.length)
    for (const result of results) {
    const title = result.title.split('/')[0].trim()
    if (!title || title.includes(':') || title.length > 48) continue
    if (excludedTitles.has(title)) continue
    if (!titleKeywords[category].some((keyword) => title.includes(keyword))) continue
    const existing = records.get(title)
    if (!existing || result.wordcount > existing.wordCount) {
      records.set(title, { title, category, wordCount: result.wordcount || 0 })
    }
  }
  }
}

await scanWorker()
for (const category of Object.keys(titleKeywords)) process.stdout.write(`${category}: ${counts.get(category) || 0} scanned results\n`)

const discovered = [...records.values()].sort((a, b) => a.category.localeCompare(b.category, 'zh-CN') || a.title.localeCompare(b.title, 'zh-CN'))
const source = `// Generated by scripts/sync-public-books.mjs on ${new Date().toISOString()}\nexport const discoveredBooks = ${JSON.stringify(discovered, null, 2)}\n`
await writeFile(join(root, 'discovered-books.mjs'), source, 'utf8')
process.stdout.write(`Generated ${discovered.length} unique public-domain root pages.\n`)
